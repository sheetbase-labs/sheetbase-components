/**
 * Build the single `sheetbase-studio` binary for one or more platforms:
 *
 *   bun scripts/build-binary.ts                 # this machine's platform
 *   bun scripts/build-binary.ts osx_arm64 windows_amd64
 *   bun scripts/build-binary.ts --all
 *
 * Each binary embeds the Studio UI, DuckDB's native binding and the SQLite,
 * Postgres and MySQL connectors (gzipped; unpacked once into the user cache
 * on first use). Output: `dist/sheetbase-studio-<version>-<platform>[.exe]`
 * plus a `.sha256` next to it.
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { gzipSync } from 'node:zlib'
import { EXTENSIONS, TARGETS, cliRoot, duckdbVersion, fetchNatives, hostTarget, type Target } from './natives'

const version = (JSON.parse(readFileSync(join(cliRoot, 'package.json'), 'utf8')) as { version: string }).version
const uiDir = join(cliRoot, '.build', 'ui')
const distDir = join(cliRoot, 'dist')

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    return statSync(path).isDirectory() ? listFiles(path) : [path]
  })
}

function gzipTo(source: string, target: string): string {
  if (!existsSync(target) || statSync(target).mtimeMs < statSync(source).mtimeMs) writeFileSync(target, gzipSync(readFileSync(source), { level: 9 }))
  return target
}

const literal = (value: string) => JSON.stringify(value)
/** Import specifiers use forward slashes on every OS. */
const spec = (path: string) => JSON.stringify(path.split(sep).join('/'))

function ensureUi() {
  if (existsSync(join(uiDir, 'standalone.html'))) return
  console.log('Building the Studio UI…')
  const result = spawnSync('bun', ['run', 'build:ui'], { cwd: cliRoot, stdio: 'inherit', shell: process.platform === 'win32' })
  if (result.status !== 0) throw new Error('UI build failed')
}

async function build(target: Target) {
  const duckdb = duckdbVersion()
  const natives = await fetchNatives(target, (line) => console.log(line))
  const stage = join(cliRoot, '.build', 'stage', target.duckdb)
  mkdirSync(stage, { recursive: true })

  const addon = gzipTo(join(natives, 'binding', 'duckdb.node'), join(stage, 'duckdb.node.gz'))
  const library = gzipTo(join(natives, 'binding', target.library), join(stage, `${target.library}.gz`))
  const extensions = EXTENSIONS.map((name) => [name, gzipTo(join(natives, 'extensions', `${name}.duckdb_extension`), join(stage, `${name}.duckdb_extension.gz`))] as const)
  const uiFiles = listFiles(uiDir).sort()

  // A content hash names the cache directory, so a new build never reuses an
  // older build's unpacked files.
  const hash = createHash('sha256')
  for (const file of [addon, library, ...extensions.map(([, path]) => path), ...uiFiles]) hash.update(readFileSync(file))
  const buildId = `${version}-${duckdb}-${target.duckdb}-${hash.digest('hex').slice(0, 12)}`

  const embedded = join(stage, 'embedded.ts')
  writeFileSync(embedded, [
    '// Generated by scripts/build-binary.ts — do not edit.',
    ...uiFiles.map((file, index) => `import ui${index} from ${spec(file)} with { type: 'file' }`),
    ...extensions.map(([name, path]) => `import ext_${name} from ${spec(path)} with { type: 'file' }`),
    `export const version = ${literal(version)}`,
    `export const duckdb = ${literal(duckdb)}`,
    `export const platform = ${literal(target.duckdb)}`,
    `export const buildId = ${literal(buildId)}`,
    `export const ui: Record<string, string> = { ${uiFiles.map((file, index) => `${literal(relative(uiDir, file).split(sep).join('/'))}: ui${index}`).join(', ')} }`,
    `export const extensions: Record<string, string> = { ${extensions.map(([name]) => `${name}: ext_${name}`).join(', ')} }`,
    '',
  ].join('\n'))

  // DuckDB's binding loads its shared library from its own directory, so both
  // are unpacked side by side before the addon is required.
  const loader = join(stage, 'duckdb-native.ts')
  writeFileSync(loader, [
    '// Generated by scripts/build-binary.ts — do not edit.',
    "import { createRequire } from 'node:module'",
    "import { join } from 'node:path'",
    `import addon from ${spec(addon)} with { type: 'file' }`,
    `import library from ${spec(library)} with { type: 'file' }`,
    `import { cacheRoot } from ${spec(join(cliRoot, 'src', 'platform.ts'))}`,
    `import { unpackOnce } from ${spec(join(cliRoot, 'src', 'unpack.ts'))}`,
    `const dir = join(cacheRoot(), ${literal(buildId)}, 'duckdb')`,
    `unpackOnce(library, join(dir, ${literal(target.library)}))`,
    "const addonPath = unpackOnce(addon, join(dir, 'duckdb.node'))",
    "if (process.platform === 'win32') process.env.PATH = dir + ';' + (process.env.PATH ?? '')",
    'module.exports = createRequire(import.meta.url)(addonPath)',
    '',
  ].join('\n'))

  // The browser-only engines Studio's data layer can lazy-load never run here.
  const stub = join(stage, 'browser-only.ts')
  writeFileSync(stub, [
    '// Generated by scripts/build-binary.ts — the in-browser engines are not part of the binary.',
    "function unavailable(): never { throw new Error('Not available in the sheetbase-studio binary.') }",
    'export const selectBundle = unavailable',
    'export const getJsDelivrBundles = unavailable',
    'export const parquetReadObjects = unavailable',
    'export const compressors = {}',
    'export class AsyncDuckDB { constructor() { unavailable() } }',
    'export class VoidLogger {}',
    'export default unavailable',
    '',
  ].join('\n'))

  mkdirSync(distDir, { recursive: true })
  const outfile = join(distDir, `sheetbase-studio-${version}-${target.duckdb}${target.duckdb.startsWith('windows') ? '.exe' : ''}`)
  rmSync(outfile, { force: true })
  const result = await Bun.build({
    entrypoints: [join(cliRoot, 'src', 'cli.ts')],
    compile: { target: target.bun as Bun.Build.CompileTarget, outfile },
    minify: true,
    plugins: [{
      name: 'sheetbase-binary',
      setup(builder) {
        builder.onResolve({ filter: /^sheetbase:embedded$/ }, () => ({ path: embedded }))
        builder.onResolve({ filter: /^@duckdb\/node-bindings-[^/]+\/duckdb\.node$/ }, () => ({ path: loader }))
        builder.onResolve({ filter: /^(@duckdb\/duckdb-wasm|hyparquet|hyparquet-compressors)$/ }, () => ({ path: stub }))
      },
    }],
  })
  if (!result.success) {
    for (const log of result.logs) console.error(log)
    throw new Error(`Build failed for ${target.duckdb}`)
  }
  const digest = createHash('sha256').update(readFileSync(outfile)).digest('hex')
  writeFileSync(`${outfile}.sha256`, `${digest}  ${relative(distDir, outfile)}\n`)
  const size = statSync(outfile).size / 1024 ** 2
  console.log(`✓ ${relative(cliRoot, outfile)} (${size.toFixed(0)} MB, build ${buildId})`)
}

if (import.meta.main) {
  const args = process.argv.slice(2)
  const targets = args.includes('--all') ? Object.values(TARGETS)
    : args.length ? args.map((name) => TARGETS[name] ?? (() => { throw new Error(`Unknown target ${name}; one of ${Object.keys(TARGETS).join(', ')}`) })())
    : [hostTarget()]
  ensureUi()
  for (const target of targets) {
    console.log(`\n${target.duckdb}:`)
    await build(target)
  }
}
